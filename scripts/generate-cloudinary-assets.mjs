import "dotenv/config";
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import pLimit from "p-limit";
import { ASSETS } from "../seed/config/assets.cloudinary.js";
import cloudinary from "../src/lib/cloudinary.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const outputFile = path.resolve(__dirname, "../seed/config/assets.cloudinary.js");
const uploadFolderRoot = "booklyx/seed-assets";
const concurrency = pLimit(3);

function requireEnv(name) {
  const value = process.env[name];
  if (!value) {
    throw new Error(`Missing required environment variable: ${name}`);
  }

  return value;
}

function sanitizeSegment(value) {
  return String(value)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .replace(/-{2,}/g, "-");
}

async function uploadRemoteImage(sourceUrl, folder, publicId) {
  const response = await fetch(sourceUrl);

  if (!response.ok) {
    throw new Error(`Failed to fetch ${sourceUrl} (${response.status} ${response.statusText})`);
  }

  const buffer = Buffer.from(await response.arrayBuffer());

  return new Promise((resolve, reject) => {
    const uploadStream = cloudinary.uploader.upload_stream(
      {
        folder,
        public_id: publicId,
        overwrite: true,
        resource_type: "image",
      },
      (error, result) => {
        if (error) {
          reject(error);
          return;
        }

        resolve(result?.secure_url ?? null);
      },
    );

    uploadStream.end(buffer);
  });
}

async function uploadAssetsNode(node, trail = []) {
  if (Array.isArray(node)) {
    return Promise.all(
      node.map((value, index) => {
        if (typeof value !== "string") {
          return value;
        }

        const folder = [uploadFolderRoot, ...trail.map(sanitizeSegment)].join("/");
        const publicId = `asset-${index + 1}`;

        return concurrency(() => uploadRemoteImage(value, folder, publicId));
      }),
    );
  }

  if (node && typeof node === "object") {
    const entries = await Promise.all(
      Object.entries(node).map(async ([key, value]) => [
        key,
        await uploadAssetsNode(value, [...trail, key]),
      ]),
    );

    return Object.fromEntries(entries);
  }

  return node;
}

function toModuleSource(data) {
  return `/**
 * Generated by scripts/generate-cloudinary-assets.mjs.
 * Do not edit manually.
 */

export const ASSETS = ${JSON.stringify(data, null, 2)};
`;
}

async function main() {
  requireEnv("CLOUDINARY_CLOUD_NAME");
  requireEnv("CLOUDINARY_API_KEY");
  requireEnv("CLOUDINARY_API_SECRET");

  const generatedAssets = await uploadAssetsNode(ASSETS);
  await fs.writeFile(outputFile, toModuleSource(generatedAssets), "utf8");

  console.log(`Cloudinary assets written to ${path.relative(process.cwd(), outputFile)}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});